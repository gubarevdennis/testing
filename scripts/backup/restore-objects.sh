#!/usr/bin/env bash
# Materialises, from the backup object pool, every object referenced by a database — used after a
# point-in-time recovery (PITR, see wal-archive.md), where no backup manifest matches the recovered state.
#
#   scripts/backup/restore-objects.sh --db postgres://kb@db/kb_pitr --pool /backups/objects --target /var/lib/kb/objects-pitr
#
# Blobs are content-addressed (key = blobs/aa/bb/<sha256>), so they are found by name; derivatives
# (thumbnails, tiles) are looked up in the pool's index.log. Every copied object is sha256-verified.
# Exit status 1 if any referenced blob is missing (derivatives that are missing are listed: they can be
# regenerated by re-uploading / background jobs, originals cannot).
#   --allow-missing   exit 0 even when blobs are missing (disaster recovery to the end of the WAL: files uploaded after the
#                     last object sync are lost; they are listed so users can be told which files to upload again)
#   --report FILE     JSON report: counts, the storage keys of missing blobs and derivatives, duration
set -euo pipefail
LOG_TAG=restore-objects
# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
DB=""; POOL=""; TARGET=""; ALLOW_MISSING=0; REPORT=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --db) DB="$2"; shift 2 ;;
    --pool) POOL="$2"; shift 2 ;;
    --target) TARGET="$2"; shift 2 ;;
    --allow-missing) ALLOW_MISSING=1; shift ;;
    --report) REPORT="$2"; shift 2 ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done
[[ -n "$DB" && -n "$POOL" && -n "$TARGET" ]] || die "usage: restore-objects.sh --db URL --pool DIR --target DIR"
need psql sha256sum awk jq
T0=$(now_ms)
mkdir -p "$TARGET/tmp" "$TARGET/blobs"
TMP="$(mktemp -d "${TMPDIR:-/tmp}/kb-robj.XXXXXX")"
trap 'rm -rf -- "$TMP"' EXIT
declare -A IDX=()
[[ -f "$POOL/index.log" ]] && while read -r sha _ key; do IDX["$key"]="$sha"; done <"$POOL/index.log"

copy() { # sha key -> 0 ok, 1 missing
  local sha="$1" key="$2" src enc=0
  case "$key" in /*|*..*) die "unsafe key: $key" ;; esac
  src="$POOL/${sha:0:2}/$sha"
  if [[ -f "$src.enc" ]]; then src="$src.enc"; enc=1; elif [[ ! -f "$src" ]]; then return 1; fi
  [[ -f "$TARGET/$key" ]] || fetch_file "$src" "$TARGET/$key" "$enc"
  printf '%s  %s\n' "$sha" "$key" >>"$TMP/check"
}
: >"$TMP/check"; : >"$TMP/missing"; : >"$TMP/dmissing"
BLOBS=0; MISSING=0; DERIV=0; DMISSING=0
while read -r sha key; do
  [[ -n "$sha" ]] || continue
  BLOBS=$((BLOBS + 1))
  copy "$sha" "$key" || { log "MISSING blob $sha ($key)"; MISSING=$((MISSING + 1)); printf '%s\n' "$key" >>"$TMP/missing"; }
done < <(psql_q "$DB" -F ' ' -c "select sha256, storage_key from blobs")
while read -r key; do
  [[ -n "$key" ]] || continue
  DERIV=$((DERIV + 1))
  sha="${IDX[$key]:-}"
  if [[ -z "$sha" ]] || ! copy "$sha" "$key"; then log "missing derivative $key (regenerable)"; DMISSING=$((DMISSING + 1)); printf '%s\n' "$key" >>"$TMP/dmissing"; fi
done < <(psql_q "$DB" -c "select storage_key from blob_derivatives")
( cd "$TARGET" && sha256sum --quiet --strict -c "$TMP/check" ) || die "copied objects failed the sha256 check"
log "objects: $BLOBS blob(s), $MISSING missing; $DERIV derivative(s), $DMISSING missing — $(( $(now_ms) - T0 )) ms"
if [[ -n "$REPORT" ]]; then
  jq -n --argjson blobs "$BLOBS" --argjson deriv "$DERIV" --argjson ms "$(( $(now_ms) - T0 ))" \
    --rawfile missing "$TMP/missing" --rawfile dmissing "$TMP/dmissing" \
    '{blobs: $blobs, missingBlobs: ($missing | split("\n") | map(select(length > 0))), derivatives: $deriv,
      missingDerivatives: ($dmissing | split("\n") | map(select(length > 0))), ms: $ms}' >"$REPORT"
fi
[[ $MISSING -eq 0 || $ALLOW_MISSING -eq 1 ]] || exit 1
